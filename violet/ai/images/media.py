"""MediaAssetStore: every image file Violet receives or produces (phase 6).

* Files live under one root (VIOLET_MEDIA_DIR, default <VIOLET_DATA_DIR>/media),
  which is git-ignored. Paths are generated by code (uuid + extension from the
  sniffed type); user / provider file names are never used. Every path is
  resolved and must stay inside the root.
* Content is validated before it is stored: magic bytes (PNG, JPEG, GIF, WEBP
  only -- no SVG / HTML / scripts), file size, width x height (read from the
  header, no decoder, so no decompression bombs).
* Writes are atomic: a 'pending' row, a temp file in the same directory, fsync,
  rename, then 'ready' with the sha256. Only 'ready' assets whose file still
  matches the sha256 can be sent.
* Originals are never modified: edits and variations are new assets that point
  to their source (source_asset_id).
* delete() removes exactly the asset's own file and marks the row deleted;
  purge_expired() does the same for assets past expires_at.
* Text about an image is not kept longer than the image (phase 7, R-P1): deleting /
  expiring an asset also erases, in one transaction, the descriptions models wrote
  about it wherever they were copied (chat history, inbound log, memory jobs ...)
  and clears the prompts / descriptions of its image tasks. purge_old_texts()
  clears image-task text older than VIOLET_IMAGE_TEXT_RETENTION_DAYS (default 30).
  The user's own words in the chat history are theirs and are not touched here.
* Image bytes and model descriptions are never written to logs.
"""

from __future__ import annotations

import hashlib
import logging
import os
import shutil
import struct
import uuid
from dataclasses import dataclass
from datetime import timedelta
from pathlib import Path
from typing import Any

from ai.memory_model import parse_time
from ai.settings import PROJECT_ROOT, env_float, env_int, env_str

logger = logging.getLogger("violet.media")

FORMATS = {"image/png": "png", "image/jpeg": "jpg", "image/gif": "gif", "image/webp": "webp"}


class MediaError(ValueError):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


@dataclass(frozen=True)
class ImageInfo:
    mime: str
    ext: str
    width: int
    height: int


def _jpeg_size(data: bytes) -> tuple[int, int]:
    i = 2
    while i + 9 < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            height, width = struct.unpack(">HH", data[i + 5:i + 9])
            return width, height
        i += 2 + length
    raise MediaError("invalid_image", "jpeg without a frame header")


def _webp_size(data: bytes) -> tuple[int, int]:
    chunk = data[12:16]
    if chunk == b"VP8X":
        return 1 + int.from_bytes(data[24:27], "little"), 1 + int.from_bytes(data[27:30], "little")
    if chunk == b"VP8 ":
        return struct.unpack("<H", data[26:28])[0] & 0x3FFF, struct.unpack("<H", data[28:30])[0] & 0x3FFF
    if chunk == b"VP8L":
        b = data[21:25]
        return 1 + (((b[1] & 0x3F) << 8) | b[0]), 1 + (((b[3] & 0x0F) << 10) | (b[2] << 2) | ((b[1] & 0xC0) >> 6))
    raise MediaError("invalid_image", "unknown webp chunk")


def sniff_image(data: bytes) -> ImageInfo:
    """Identify an image by its bytes (never by name or declared type) and read its size."""
    if not data or len(data) < 16:
        raise MediaError("invalid_image", "empty or truncated file")
    try:
        if data.startswith(b"\x89PNG\r\n\x1a\n") and data[12:16] == b"IHDR":
            w, h = struct.unpack(">II", data[16:24])
            mime = "image/png"
        elif data.startswith(b"\xff\xd8\xff"):
            w, h = _jpeg_size(data)
            mime = "image/jpeg"
        elif data[:6] in (b"GIF87a", b"GIF89a"):
            w, h = struct.unpack("<HH", data[6:10])
            mime = "image/gif"
        elif data[:4] == b"RIFF" and data[8:12] == b"WEBP":
            w, h = _webp_size(data)
            mime = "image/webp"
        else:
            raise MediaError("unsupported_format", "not a PNG / JPEG / GIF / WEBP image")
    except struct.error:
        raise MediaError("invalid_image", "corrupt image header") from None
    if w <= 0 or h <= 0:
        raise MediaError("invalid_image", "image has no size")
    return ImageInfo(mime, FORMATS[mime], int(w), int(h))


def validate_image(data: bytes, max_bytes: int | None = None, max_pixels: int | None = None,
                   allowed: tuple[str, ...] | None = None) -> ImageInfo:
    max_bytes = max_bytes or env_int("VIOLET_IMAGE_MAX_BYTES", 10_000_000)
    max_pixels = max_pixels or env_int("VIOLET_IMAGE_MAX_PIXELS", 40_000_000)
    if len(data) > max_bytes:
        raise MediaError("too_large", f"image larger than {max_bytes} bytes")
    info = sniff_image(data)
    if allowed and info.mime not in allowed:
        raise MediaError("unsupported_format", f"{info.mime} is not accepted here")
    if info.width * info.height > max_pixels:
        raise MediaError("too_many_pixels", f"image larger than {max_pixels} pixels")
    return info


def media_root() -> Path:
    override = env_str("VIOLET_MEDIA_DIR", "")
    if override:
        return Path(override).resolve()
    data_dir = env_str("VIOLET_DATA_DIR", "") or str(PROJECT_ROOT / "data")
    return (Path(data_dir) / "media").resolve()


class MediaAssetStore:
    DIRECTIONS = ("inbound", "outbound", "reference")

    def __init__(self, db, root: Path | None = None):
        self.db = db
        self.root = (root or media_root()).resolve()

    # -- paths ---------------------------------------------------------------------
    def _inside(self, path: Path) -> Path:
        resolved = path.resolve()
        if resolved != self.root and self.root not in resolved.parents:
            raise MediaError("unsafe_path", "path outside the media directory")
        return resolved

    def path_of(self, asset: dict[str, Any]) -> Path:
        return self._inside(self.root / asset["storage_path"])

    # -- rows ------------------------------------------------------------------------
    def get(self, asset_id: int) -> dict[str, Any] | None:
        return self.db.fetch_one("SELECT * FROM media_assets WHERE id = ?", (asset_id,))

    def list(self, limit: int = 100, direction: str | None = None, include_deleted: bool = False) -> list[dict[str, Any]]:
        clauses, params = [], []
        if direction:
            clauses.append("direction = ?")
            params.append(direction)
        if not include_deleted:
            clauses.append("status != 'deleted'")
        where = f"WHERE {' AND '.join(clauses)}" if clauses else ""
        return self.db.fetch_all(f"SELECT * FROM media_assets {where} ORDER BY id DESC LIMIT ?", (*params, limit))

    def _set(self, asset_id: int, **fields: Any) -> None:
        fields["updated_at"] = self.db.now()
        self.db.execute(f"UPDATE media_assets SET {', '.join(f'{k} = ?' for k in fields)} WHERE id = ?",
                        (*fields.values(), asset_id))

    # -- store -----------------------------------------------------------------------
    def store_bytes(self, data: bytes, *, direction: str, media_kind: str, ai_generated: bool,
                    task_id: str | None = None, provider_id: str | None = None, model_id: str | None = None,
                    source_inbound_id: int | None = None, source_message_id: int | None = None,
                    source_asset_id: int | None = None, life_event_id: int | None = None,
                    scene_kind: str | None = None, generated_prompt: str | None = None, caption: str | None = None,
                    retention_days: float | None = None, max_bytes: int | None = None) -> dict[str, Any]:
        if direction not in self.DIRECTIONS:
            raise MediaError("invalid", "unknown direction")
        info = validate_image(data, max_bytes=max_bytes)
        digest = hashlib.sha256(data).hexdigest()
        now = self.db.now()
        if retention_days is None:
            retention_days = env_float("VIOLET_MEDIA_INBOUND_RETENTION_DAYS", 7) if direction == "inbound" else \
                env_float("VIOLET_MEDIA_GENERATED_RETENTION_DAYS", 30)
        expires = (parse_time(now) + timedelta(days=retention_days)).isoformat() if retention_days > 0 else None
        relative = Path(direction) / now[:7] / f"{uuid.uuid4().hex}.{info.ext}"
        target = self._inside(self.root / relative)
        cursor = self.db.execute(
            """INSERT INTO media_assets (asset_uid, task_id, provider_id, model_id, direction, media_kind, sha256,
                   storage_path, mime_type, width, height, file_size, source_inbound_id, source_message_id,
                   source_asset_id, life_event_id, scene_kind, generated_prompt, caption, ai_generated, status,
                   send_status, created_at, updated_at, expires_at)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'pending', 'not_sent', ?, ?, ?)""",
            (uuid.uuid4().hex, task_id, provider_id, model_id, direction, media_kind, digest, relative.as_posix(),
             info.mime, info.width, info.height, len(data), source_inbound_id, source_message_id, source_asset_id,
             life_event_id, scene_kind, generated_prompt, caption, 1 if ai_generated else 0, now, now, expires))
        asset_id = int(cursor.lastrowid)
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_suffix(target.suffix + ".part")
        try:
            with open(tmp, "wb") as f:
                f.write(data)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, target)
        except OSError as exc:
            if tmp.exists():
                tmp.unlink()
            self._set(asset_id, status="failed")
            raise MediaError("write_failed", f"could not store image ({exc.__class__.__name__})") from None
        self._set(asset_id, status="ready")
        return self.get(asset_id)

    def store_file(self, path: str | os.PathLike[str], **kwargs: Any) -> dict[str, Any]:
        """Copy (never move or modify) a downloaded file into the store."""
        src = Path(path)
        size = src.stat().st_size
        limit = kwargs.get("max_bytes") or env_int("VIOLET_IMAGE_MAX_BYTES", 10_000_000)
        if size > limit:
            raise MediaError("too_large", f"image larger than {limit} bytes")
        return self.store_bytes(src.read_bytes(), **kwargs)

    # -- read / send ---------------------------------------------------------------------
    def read_bytes(self, asset: dict[str, Any]) -> bytes:
        if asset["status"] != "ready":
            raise MediaError("not_ready", f"asset {asset['id']} is {asset['status']}")
        data = self.path_of(asset).read_bytes()
        if hashlib.sha256(data).hexdigest() != asset["sha256"]:
            raise MediaError("corrupt", f"asset {asset['id']} does not match its checksum")
        return data

    def sendable(self, asset_id: int) -> tuple[dict[str, Any] | None, str | None]:
        """(asset, None) if this outbound image is complete and intact, else (asset, reason)."""
        asset = self.get(asset_id)
        if asset is None:
            return None, "unknown asset"
        if asset["direction"] != "outbound":
            return asset, "only outbound images can be sent"
        try:
            self.read_bytes(asset)
        except (MediaError, OSError) as exc:
            return asset, f"not sendable: {exc}"
        return asset, None

    def mark_send(self, asset_id: int, status: str, error: str | None = None) -> None:
        fields: dict[str, Any] = {"send_status": status, "send_error": error}
        if status == "sent":
            fields["sent_at"] = self.db.now()
        self._set(asset_id, **fields)

    def link_message(self, inbound_ids: list[int], message_id: int) -> None:
        if inbound_ids:
            self.db.execute(
                f"UPDATE media_assets SET source_message_id = ? WHERE source_inbound_id IN ({', '.join('?' for _ in inbound_ids)})",
                (message_id, *inbound_ids))

    # -- delete -----------------------------------------------------------------------
    def delete(self, asset_id: int, reason: str = "dashboard") -> bool:
        asset = self.get(asset_id)
        if asset is None or asset["status"] == "deleted":
            return False
        try:
            path = self.path_of(asset)
            if path.is_file():
                path.unlink()
        except MediaError:
            logger.error("media asset %s has an unsafe path; row marked deleted, nothing removed", asset_id)
        except OSError as exc:
            # e.g. the file is open elsewhere (Windows): keep the row so the file is not orphaned
            raise MediaError("delete_failed", f"could not delete the file ({exc.__class__.__name__}); try again later") from None
        # the file is gone; the rows and every text about the image go together (retry-safe if this fails)
        with self.db.transaction():
            self._scrub_texts(asset)
            self._set(asset_id, status="deleted", deleted_reason=reason[:100], generated_prompt=None)
        return True

    def _tasks_of(self, asset: dict[str, Any]) -> list[dict[str, Any]]:
        import json
        tasks = []
        for task in self.db.fetch_all("SELECT * FROM image_tasks WHERE task_id = ? OR input_asset_ids LIKE ?",
                                      (asset.get("task_id") or "", f"%{asset['id']}%")):
            inputs = json.loads(task["input_asset_ids"] or "[]")
            if task["task_id"] == asset.get("task_id") or asset["id"] in inputs:
                tasks.append(task)
        return tasks

    def _scrub_texts(self, asset: dict[str, Any]) -> int:
        """Inside a transaction: erase model-written descriptions of this image and its tasks' text."""
        from ai.profile_store import redact_everywhere
        tasks = self._tasks_of(asset)
        descriptions = [t["result_text"] for t in tasks if t["result_text"] and len(t["result_text"]) >= 4]
        touched = redact_everywhere(self.db, descriptions) if descriptions else 0
        for task in tasks:
            self.db.execute("UPDATE image_tasks SET prompt = NULL, result_text = NULL, scene = NULL, updated_at = ? "
                            "WHERE task_id = ?", (self.db.now(), task["task_id"]))
        return touched

    def purge_old_texts(self, days: float | None = None) -> int:
        """Clear image-task prompts / descriptions older than the retention period (and their copies)."""
        from ai.profile_store import redact_everywhere
        days = env_float("VIOLET_IMAGE_TEXT_RETENTION_DAYS", 30) if days is None else days
        cutoff = (parse_time(self.db.now()) - timedelta(days=days)).isoformat()
        old = [t for t in self.db.fetch_all("SELECT * FROM image_tasks WHERE (prompt IS NOT NULL OR result_text IS NOT NULL)")
               if parse_time(t["created_at"]) < parse_time(cutoff)]
        if not old:
            return 0
        with self.db.transaction():
            redact_everywhere(self.db, [t["result_text"] for t in old if t["result_text"] and len(t["result_text"]) >= 4])
            for task in old:
                self.db.execute("UPDATE image_tasks SET prompt = NULL, result_text = NULL, scene = NULL, updated_at = ? "
                                "WHERE task_id = ?", (self.db.now(), task["task_id"]))
        return len(old)

    def purge_expired(self) -> int:
        now = parse_time(self.db.now())
        count = 0
        for asset in self.db.fetch_all("SELECT * FROM media_assets WHERE status != 'deleted' AND expires_at IS NOT NULL"):
            if parse_time(asset["expires_at"]) <= now:
                try:
                    if self.delete(asset["id"], "expired"):
                        count += 1
                except MediaError:
                    logger.warning("expired media asset %s could not be removed yet", asset["id"])
        return count

    def usage(self) -> dict[str, Any]:
        row = self.db.fetch_one("SELECT COUNT(*) AS n, COALESCE(SUM(file_size), 0) AS bytes FROM media_assets "
                                "WHERE status = 'ready'")
        return {"assets": row["n"], "bytes": row["bytes"], "root_exists": self.root.exists(),
                "free_bytes": shutil.disk_usage(self.root).free if self.root.exists() else None}
